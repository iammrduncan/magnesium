#!/usr/bin/env node
// @effect-diagnostics nodeBuiltinImport:off globalConsole:off globalDate:off
// magnesium: a read-only merge rehearsal against upstream (doc 11, sync policy).
//
//   node scripts/merge-rehearsal.ts [--ref upstream/main] [--out <dir>]
//
// Merges `--ref` into a detached copy of HEAD in a throwaway worktree with
// `git merge --no-commit`, writes a per-file conflict report (report.md and
// report.json) to `--out`, then aborts the merge and removes the worktree.
// No branch, ref or file in this checkout changes.
import * as NodeChildProcess from "node:child_process";
import * as NodeFS from "node:fs";
import * as NodeOS from "node:os";
import * as NodePath from "node:path";

import { isRenameOwned } from "./rename-upstream.ts";
import { isStripped, STRIP_PATCHED_FILES } from "./strip-upstream.ts";

// Regenerated by scripts/merge-upstream.ts, so a conflict in them costs nothing.
export const REGENERATED_FILES = ["pnpm-lock.yaml", "apps/web/src/routeTree.gen.ts"];

// Upstream files Magnesium replaced outright; a conflict keeps ours.
export const KEEP_OURS_FILES = ["README.md"];

/** Hand edits in files that cannot hold a comment, with what each one does. */
export const UNMARKABLE_EDITS: Readonly<Record<string, string>> = {
  LICENSE: "adds the copyright line for Magnesium's own work",
  "package.json": "adds check:public (scripts/check-public.ts)",
  "apps/server/package.json": "adds @magnesium/server (doc 11)",
  "apps/server/src/provider/model-manifest.json":
    "marks OpenCode 2.0.32 supported for this release, which runs Orchestrator V2 (D69)",
  "apps/web/package.json":
    "drops @clerk/electron and @clerk/react (D13); adds @magnesium/web and @magnesium/contracts (doc 11)",
  "apps/web/public/manifest.webmanifest": "starts the installed app on Home (/home, goal 06)",
};

const TRACK_ZONE = ["apps/server/", "packages/"];
const OWN_ZONE = ["apps/web/"];

export type ConflictKind = "stripped" | "scripted" | "regenerated" | "ours" | "real";

export interface FileConflict {
  readonly file: string;
  /** Porcelain v1 unmerged status, e.g. UU, AA, DU, UD. */
  readonly status: string;
  readonly hunks: number;
  readonly kind: ConflictKind;
  readonly zone: "track" | "own" | "other";
}

export interface RehearsalReport {
  readonly ref: string;
  readonly refCommit: string;
  readonly head: string;
  readonly upstreamCommits: number;
  readonly changedFiles: number;
  readonly conflicts: ReadonlyArray<FileConflict>;
}

const run = (cwd: string, command: string, args: ReadonlyArray<string>) =>
  NodeChildProcess.spawnSync(command, args, {
    cwd,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  });

const git = (cwd: string, args: ReadonlyArray<string>): string => {
  const result = run(cwd, "git", args);
  if (result.status !== 0) {
    throw new Error(`git ${args.join(" ")} failed: ${result.stderr}`);
  }
  return result.stdout;
};

/**
 * How a conflicted file gets resolved. Files the strip and rename scripts edit
 * take upstream's side and the scripts run again, unless the file also has a
 * hand-written `magnesium:` edit, which a person has to merge.
 */
export function classifyConflict(file: string, hasMarker: boolean): ConflictKind {
  if (isStripped(file)) return "stripped";
  if (REGENERATED_FILES.includes(file)) return "regenerated";
  if (KEEP_OURS_FILES.includes(file)) return "ours";
  // A hand edit no comment can mark is a person's to merge, like a marked one.
  if (UNMARKABLE_EDITS[file] !== undefined) return "real";
  if (!hasMarker && (isRenameOwned(file) || STRIP_PATCHED_FILES.includes(file))) {
    return "scripted";
  }
  return "real";
}

/** True when the committed file carries a hand-written Magnesium edit. */
export function hasMarkerAtHead(cwd: string, file: string): boolean {
  const result = run(cwd, "git", ["show", `HEAD:${file}`]);
  return result.status === 0 && result.stdout.includes("magnesium:");
}

const zoneOf = (file: string): FileConflict["zone"] =>
  TRACK_ZONE.some((prefix) => file.startsWith(prefix))
    ? "track"
    : OWN_ZONE.some((prefix) => file.startsWith(prefix))
      ? "own"
      : "other";

/** Unmerged entries from `git status --porcelain=v1 -z`. */
export function parseUnmerged(porcelain: string): Array<{ status: string; file: string }> {
  const unmerged = new Set(["DD", "AU", "UD", "UA", "DU", "AA", "UU"]);
  return porcelain
    .split("\0")
    .filter((entry) => entry.length > 3)
    .map((entry) => ({ status: entry.slice(0, 2), file: entry.slice(3) }))
    .filter((entry) => unmerged.has(entry.status));
}

const countHunks = (path: string): number => {
  if (!NodeFS.existsSync(path)) return 0;
  const content = NodeFS.readFileSync(path, "utf8");
  return content.split("\n").filter((line) => line.startsWith("<<<<<<< ")).length;
};

export function rehearse(repo: string, ref: string): RehearsalReport {
  const head = git(repo, ["rev-parse", "HEAD"]).trim();
  const refCommit = git(repo, ["rev-parse", `${ref}^{commit}`]).trim();
  const upstreamCommits = Number(git(repo, ["rev-list", "--count", `HEAD..${refCommit}`]).trim());
  const worktree = NodeFS.mkdtempSync(NodePath.join(NodeOS.tmpdir(), "magnesium-rehearsal-"));
  git(repo, ["worktree", "add", "--detach", worktree, head]);
  try {
    const merge = run(worktree, "git", [
      "-c",
      "user.name=merge-rehearsal",
      "-c",
      "user.email=merge-rehearsal@localhost",
      "merge",
      "--no-commit",
      "--no-ff",
      refCommit,
    ]);
    if (merge.status !== 0 && !/CONFLICT/.test(merge.stdout + merge.stderr)) {
      throw new Error(`git merge failed: ${merge.stderr || merge.stdout}`);
    }
    const conflicts = parseUnmerged(git(worktree, ["status", "--porcelain=v1", "-z"])).map(
      ({ status, file }): FileConflict => ({
        file,
        status,
        hunks: countHunks(NodePath.join(worktree, file)),
        kind: classifyConflict(file, hasMarkerAtHead(worktree, file)),
        zone: zoneOf(file),
      }),
    );
    const changedFiles = git(worktree, ["diff", "--cached", "--name-only", head])
      .split("\n")
      .filter((line) => line !== "").length;
    return { ref, refCommit, head, upstreamCommits, changedFiles, conflicts };
  } finally {
    run(worktree, "git", ["merge", "--abort"]);
    run(repo, "git", ["worktree", "remove", "--force", worktree]);
    NodeFS.rmSync(worktree, { recursive: true, force: true });
  }
}

export function formatReport(report: RehearsalReport, date: string): string {
  const real = report.conflicts.filter((conflict) => conflict.kind === "real");
  const count = (kind: ConflictKind) =>
    report.conflicts.filter((conflict) => conflict.kind === kind).length;
  const out = [
    `# Merge rehearsal, ${date}`,
    "",
    `Merging \`${report.ref}\` (${report.refCommit.slice(0, 10)}) into HEAD (${report.head.slice(0, 10)}):`,
    `${report.upstreamCommits} upstream commits, ${report.changedFiles} files changed.`,
    "",
    `- Real conflicts: ${real.length} files, ${real.reduce((sum, conflict) => sum + conflict.hunks, 0)} hunks`,
    `- In stripped paths (the strip script resolves them): ${count("stripped")}`,
    `- In files only our scripts edit (take upstream's, re-run them): ${count("scripted")}`,
    `- In regenerated files (lockfile, route tree): ${count("regenerated")}`,
    `- In files we replaced outright (keep ours): ${count("ours")}`,
    "",
  ];
  if (report.conflicts.length > 0) {
    out.push("| File | Status | Hunks | Kind | Zone |", "| --- | --- | --- | --- | --- |");
    const order: Record<ConflictKind, number> = {
      real: 0,
      scripted: 1,
      regenerated: 2,
      ours: 3,
      stripped: 4,
    };
    const sorted = [...report.conflicts].toSorted(
      (a, b) => order[a.kind] - order[b.kind] || a.file.localeCompare(b.file),
    );
    for (const conflict of sorted) {
      out.push(
        `| \`${conflict.file}\` | ${conflict.status} | ${conflict.hunks} | ${conflict.kind} | ${conflict.zone} |`,
      );
    }
  }
  return out.join("\n");
}

const readFlag = (args: ReadonlyArray<string>, name: string): string | undefined => {
  const index = args.indexOf(name);
  return index === -1 ? undefined : args[index + 1];
};

if (import.meta.main) {
  const args = process.argv.slice(2);
  const repo = NodePath.resolve(import.meta.dirname, "..");
  const ref = readFlag(args, "--ref") ?? "upstream/main";
  const date = new Date().toISOString().slice(0, 10);
  const out =
    readFlag(args, "--out") ?? NodePath.join(NodeOS.tmpdir(), `magnesium-merge-rehearsal-${date}`);
  const report = rehearse(repo, ref);
  NodeFS.mkdirSync(out, { recursive: true });
  const markdown = formatReport(report, date);
  NodeFS.writeFileSync(NodePath.join(out, "report.md"), `${markdown}\n`);
  NodeFS.writeFileSync(NodePath.join(out, "report.json"), `${JSON.stringify(report, null, 2)}\n`);
  console.log(markdown);
  console.log(`\nReport written to ${out}`);
}
